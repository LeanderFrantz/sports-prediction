#!/usr/bin/env bash
# Install the LaunchAgent that mirrors the S3 odds archive to this machine.
#
# Why this exists rather than a plist pointing straight at the repo:
#
# macOS TCC protects ~/Documents from background processes, and that covers
# *executing* a file stored there, not just writing to it. A LaunchAgent whose
# ProgramArguments point at scripts/sync_odds_archive.sh inside this repo dies
# with exit code 126 and "Operation not permitted" before the script runs at
# all — so no amount of redirecting the script's output helps.
#
# The fix is to keep the agent's executable and its data outside the protected
# directory. This installs a copy of the sync script under Application Support,
# writes a plist that passes the bucket and destination as environment
# variables (the copy cannot read the repo's .env either), and symlinks
# data/raw back into the repo so notebooks keep the familiar path.
#
# Re-run after changing scripts/sync_odds_archive.sh to push the new version.
set -euo pipefail

AGENT_LABEL="de.frantz.odds-sync"
SUPPORT_DIR="$HOME/Library/Application Support/sports-prediction"
ARCHIVE_DIR="$SUPPORT_DIR/raw"
LOG_FILE="$HOME/Library/Logs/odds-sync.log"
PLIST="$HOME/Library/LaunchAgents/$AGENT_LABEL.plist"

# Hour of the day the agent syncs. launchd fires a missed run when the machine
# next wakes or you next log in, and coalesces several missed firings into one.
SYNC_HOUR="${SYNC_HOUR:-18}"

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"

cd "$REPO_ROOT"
[ -f .env ] || { echo "Missing .env — copy .env.example first." >&2; exit 1; }
set -a
# shellcheck disable=SC1091
source .env
set +a

if [ -z "${ODDS_ARCHIVE_BUCKET:-}" ]; then
  echo "ODDS_ARCHIVE_BUCKET is not set in .env — nothing to sync." >&2
  exit 1
fi

AWS_BIN="$(command -v aws 2>/dev/null || true)"
[ -n "$AWS_BIN" ] || { echo "AWS CLI not found." >&2; exit 1; }

echo "==> Installing sync script to Application Support..."
mkdir -p "$SUPPORT_DIR" "$ARCHIVE_DIR" "$(dirname "$LOG_FILE")"
cp "$SCRIPT_DIR/sync_odds_archive.sh" "$SUPPORT_DIR/sync_odds_archive.sh"
chmod +x "$SUPPORT_DIR/sync_odds_archive.sh"

echo "==> Linking data/raw -> $ARCHIVE_DIR"
# A real directory here would shadow the link and silently go stale.
if [ -e "$REPO_ROOT/data/raw" ] && [ ! -L "$REPO_ROOT/data/raw" ]; then
  echo "    data/raw is a real directory; moving its contents into the archive."
  mkdir -p "$ARCHIVE_DIR"
  find "$REPO_ROOT/data/raw" -mindepth 1 -maxdepth 1 -exec mv {} "$ARCHIVE_DIR/" \;
  rmdir "$REPO_ROOT/data/raw"
fi
mkdir -p "$REPO_ROOT/data"
ln -sfn "$ARCHIVE_DIR" "$REPO_ROOT/data/raw"

echo "==> Writing $PLIST"
mkdir -p "$(dirname "$PLIST")"
cat > "$PLIST" <<PLIST_EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!-- Generated by scripts/install_sync_agent.sh — edit that, not this. -->
<plist version="1.0">
<dict>
    <key>Label</key>
    <string>$AGENT_LABEL</string>

    <key>ProgramArguments</key>
    <array>
        <string>$SUPPORT_DIR/sync_odds_archive.sh</string>
    </array>

    <key>StartCalendarInterval</key>
    <dict>
        <key>Hour</key><integer>$SYNC_HOUR</integer>
        <key>Minute</key><integer>0</integer>
    </dict>

    <key>RunAtLoad</key>
    <true/>
    <key>KeepAlive</key>
    <false/>

    <!-- The installed copy cannot read the repo's .env (same TCC restriction
         that blocks executing from there), so configuration is passed in.
         PATH is set because launchd hands jobs a minimal environment. -->
    <key>EnvironmentVariables</key>
    <dict>
        <key>ODDS_ARCHIVE_BUCKET</key>
        <string>$ODDS_ARCHIVE_BUCKET</string>
        <key>ODDS_ARCHIVE_LOCAL_DIR</key>
        <string>$ARCHIVE_DIR</string>
        <key>PATH</key>
        <string>$(dirname "$AWS_BIN"):/usr/bin:/bin:/usr/sbin:/sbin</string>
    </dict>

    <key>StandardOutPath</key>
    <string>$LOG_FILE</string>
    <key>StandardErrorPath</key>
    <string>$LOG_FILE</string>
</dict>
</plist>
PLIST_EOF

plutil -lint "$PLIST" >/dev/null

echo "==> Loading the agent..."
launchctl bootout "gui/$(id -u)/$AGENT_LABEL" 2>/dev/null || true
launchctl bootstrap "gui/$(id -u)" "$PLIST"

# RunAtLoad fires on bootstrap, but kickstart makes the first run synchronous
# so a failure shows up here instead of silently in the log.
launchctl kickstart -p "gui/$(id -u)/$AGENT_LABEL" >/dev/null 2>&1 || true
sleep 3

EXIT_CODE="$(launchctl print "gui/$(id -u)/$AGENT_LABEL" 2>/dev/null \
  | awk '/last exit code/ {print $NF; exit}')"

echo
echo "    Agent:       $AGENT_LABEL (daily at ${SYNC_HOUR}:00, and at login)"
echo "    Archive:     $ARCHIVE_DIR"
echo "    Repo link:   data/raw -> $ARCHIVE_DIR"
echo "    Log:         $LOG_FILE"
echo "    Last exit:   ${EXIT_CODE:-unknown}"
echo
if [ "${EXIT_CODE:-1}" = "0" ]; then
  tail -2 "$LOG_FILE" 2>/dev/null || true
else
  echo "Agent did not exit cleanly. Recent log:" >&2
  tail -5 "$LOG_FILE" 2>/dev/null || echo "(log empty — TCC may still be blocking)" >&2
  exit 1
fi
